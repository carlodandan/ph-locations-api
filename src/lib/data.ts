/**
 * A flat search index built once at module load time.
 *
 * Each entry stores the lowercased name alongside the full SearchResult so
 * that searches can be performed with a simple `includes()` check without
 * re-lowercasing on every request.
 */
interface SearchIndexEntry {
  nameLower: string;
  result: SearchResult;
}

let _searchIndex: SearchIndexEntry[] | null = null;

function buildSearchIndex(): SearchIndexEntry[] {
  const index: SearchIndexEntry[] = [];
  const regions = getRegions();

  // Add regions themselves
  for (const region of regions) {
    index.push({
      nameLower: region.name.toLowerCase(),
      result: {
        type: "region",
        name: region.name,
        slug: region.slug,
        region: { name: region.name, slug: region.slug },
        province: null,
      },
    });
  }

  // Add all locations
  for (const region of regions) {
    const data = getRegionData(region.slug);
    if (!data) continue;

    const locations = flattenLocations(data);
    for (const loc of locations) {
      index.push({
        nameLower: loc.name.toLowerCase(),
        result: {
          type: loc.type,
          name: loc.name,
          slug: loc.slug,
          region: { name: region.name, slug: region.slug },
          province: loc.province,
          zip_code: loc.zip_code,
        },
      });
    }
  }

  return index;
}

/**
 * Return the singleton search index (lazy-initialised on first call).
 */
export function getSearchIndex(): SearchIndexEntry[] {
  if (!_searchIndex) {
    _searchIndex = buildSearchIndex();
  }
  return _searchIndex;
}

/**
 * Search across regions and locations.
 *
 * @param query  Raw search string (will be lowercased internally)
 * @returns      Array of matching SearchResult objects
 */
export function search(query: string): SearchResult[] {
  const q = query.toLowerCase();
  const index = getSearchIndex();
  const results: SearchResult[] = [];

  for (const entry of index) {
    if (entry.nameLower.includes(q)) {
      results.push(entry.result);
    }
  }

  return results;
}

// ---------------------------------------------------------------------------
// Barangay lookup
// ---------------------------------------------------------------------------

/** Return the barangays for a specific location within a region. */
export function getBarangays(
  regionSlug: string,
  locationSlug: string,
): Barangay[] | null {
  const barangayFile = BARANGAY_DATA_MAP[regionSlug];
  if (!barangayFile) return null;

  const names = barangayFile.locations[locationSlug];
  if (!names) return null;

  return names.map((name) => ({ name, slug: toSlug(name) }));
}
