/** Return the list of all regions. */
export function getRegions(): Region[] {
  return regionsJson as Region[];
}

/** Return the region metadata for a given slug. */
export function getRegion(slug: string): Region | null {
  const regions = getRegions();
  return regions.find((r) => r.slug === slug) ?? null;
}

/** Return the raw region data object for a given slug. */
export function getRegionData(slug: string): RawRegionData | null {
  return REGION_DATA_MAP[slug] ?? null;
}

