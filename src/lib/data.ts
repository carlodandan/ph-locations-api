// Data normalisation
// ---------------------------------------------------------------------------

/**
 * Flatten a raw region data object into a consistent array of Location objects.
 * Appends province slugs for disambiguation when needed.
 */
export function flattenLocations(data: RawRegionData): Location[] {
  // --- First pass: build raw entries ---
  interface RawEntry {
    name: string;
    baseSlug: string;
    type: "city" | "municipality";
    zip_code: string | null;
    province: string | null;
  }

  const raw: RawEntry[] = [];

  if (data.provinces) {
    for (const province of data.provinces) {
      const provinceName = province.province;

      for (const city of province.cities ?? []) {
        raw.push({
          name: city.city,
          baseSlug: toSlug(city.city),
          type: "city",
          zip_code: city.zip_code ?? null,
          province: provinceName,
        });
      }

      for (const municipality of province.municipalities ?? []) {
        raw.push({
          name: municipality.municipality,
          baseSlug: toSlug(municipality.municipality),
          type: "municipality",
          zip_code: municipality.zip_code ?? null,
          province: provinceName,
        });
      }
    }
  } else {
    for (const city of data.cities ?? []) {
      raw.push({
        name: city.city,
        baseSlug: toSlug(city.city),
        type: "city",
        zip_code: city.zip_code ?? null,
        province: null,
      });
    }

    for (const municipality of data.municipalities ?? []) {
      raw.push({
        name: municipality.municipality,
        baseSlug: toSlug(municipality.municipality),
        type: "municipality",
        zip_code: municipality.zip_code ?? null,
        province: null,
      });
    }
  }

  // --- Second pass: count duplicate base slugs ---
  const slugCount = new Map<string, number>();
  for (const entry of raw) {
    slugCount.set(entry.baseSlug, (slugCount.get(entry.baseSlug) ?? 0) + 1);
  }

  // --- Third pass: assign final slugs, disambiguating duplicates ---
  const locations: Location[] = [];
  for (const entry of raw) {
    const count = slugCount.get(entry.baseSlug) ?? 1;
    let finalSlug: string;

    if (count > 1 && entry.province !== null) {
      // Append province slug to disambiguate — double-hyphen separator
      finalSlug = `${entry.baseSlug}--${toSlug(entry.province)}`;
    } else {
      finalSlug = entry.baseSlug;
    }

    locations.push({
      name: entry.name,
      slug: finalSlug,
      type: entry.type,
      zip_code: entry.zip_code,
      province: entry.province,
    });
  }

  return locations;
}

